import { DatabaseSync } from 'node:sqlite'
import { describe, expect, it } from 'vitest'
import type { CreateTableAction, TableAction } from '../../shared/types'
import { DIALECTS } from '../dialect'
import { changeTable, createTableSql } from '../tableSchema'
import { fakeDriver, table } from './fakeDriver'

const action: CreateTableAction = {
  kind: 'create',
  schema: 'main',
  table: 'events',
  columns: [
    { name: 'id', type: '', nullable: false, primaryKey: true, autoIncrement: true },
    { name: 'created_at', type: 'DATETIME', nullable: false, primaryKey: false, defaultValue: 'current_timestamp' },
    { name: 'state', type: 'VARCHAR(20)', nullable: false, primaryKey: false, defaultValue: "'it''s pending'" }
  ],
  foreignKeys: []
}

describe('create table SQL', () => {
  it.each([
    ['mysql', 'INT NOT NULL AUTO_INCREMENT', 'PRIMARY KEY (`id`)'],
    ['postgres', 'INTEGER GENERATED BY DEFAULT AS IDENTITY', 'PRIMARY KEY ("id")'],
    ['mssql', 'INT IDENTITY(1,1) NOT NULL', 'PRIMARY KEY ([id])']
  ] as const)('generates the %s identity and timestamp default', (kind, identity, primaryKey) => {
    const timestampType = { mysql: 'TIMESTAMP', postgres: 'TIMESTAMP WITH TIME ZONE', mssql: 'DATETIME2' }[kind]
    const sql = createTableSql(DIALECTS[kind], {
      ...action,
      columns: [action.columns[0], { ...action.columns[1], type: timestampType }, action.columns[2]]
    })
    expect(sql).toContain(identity)
    expect(sql).toContain(primaryKey)
    expect(sql).toContain(`${timestampType} NOT NULL DEFAULT CURRENT_TIMESTAMP`)
    expect(sql).toContain("DEFAULT " + (kind === 'mssql' ? 'N' : '') + "'it''s pending'")
  })

  it('creates a SQLite table that assigns IDs and applies defaults', () => {
    using db = new DatabaseSync(':memory:')
    db.exec(createTableSql(DIALECTS.sqlite, action))
    db.exec('INSERT INTO events DEFAULT VALUES')
    db.exec('INSERT INTO events DEFAULT VALUES')
    expect(db.prepare('SELECT * FROM events ORDER BY id').all()).toEqual([
      { id: 1, state: "it's pending", created_at: expect.any(String) },
      { id: 2, state: "it's pending", created_at: expect.any(String) }
    ])
  })

  it('rejects a default containing SQL beyond a supported literal or keyword', () => {
    expect(() => createTableSql(DIALECTS.sqlite, {
      ...action,
      columns: [{ ...action.columns[2], defaultValue: "'pending' CHECK (1)" }]
    })).toThrow('single-quoted string')
  })
})

describe('add column defaults', () => {
  const addColumn: TableAction = {
    kind: 'addColumn',
    schema: 'main',
    table: 'events',
    column: { name: 'created_at', type: 'DATETIME', nullable: true, defaultValue: ' current_timestamp ' }
  }

  it('rejects a non-constant default before executing an SQLite schema change', async () => {
    const driver = fakeDriver([table('main', 'events', [])], 'sqlite')
    await expect(changeTable(driver, addColumn)).rejects.toThrow('SQLite requires a constant default')
    expect(driver.executed).toHaveLength(0)
  })

  it('adds a literal default to a populated SQLite table', async () => {
    using db = new DatabaseSync(':memory:')
    db.exec('CREATE TABLE events (id INTEGER PRIMARY KEY); INSERT INTO events DEFAULT VALUES')
    const driver = fakeDriver([table('main', 'events', [])], 'sqlite')
    await changeTable(driver, {
      ...addColumn, column: { name: 'state', type: 'TEXT', nullable: false, defaultValue: "'pending'" }
    })
    db.exec(driver.executed[0].text)
    expect(db.prepare('SELECT state FROM events').get()).toEqual({ state: 'pending' })
  })

  it('keeps the timestamp default available when adding a MySQL column', async () => {
    const driver = fakeDriver([table('main', 'events', [])], 'mysql')
    await changeTable(driver, addColumn)
    expect(driver.executed[0].text).toContain('DEFAULT CURRENT_TIMESTAMP')
  })
})
